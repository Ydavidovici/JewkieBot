// Turn a tuned params file into the engine's compiled default evaluation,
// src/evalDefaults.h, laid out by section so a diff of the defaults is
// readable (each piece-square table as an 8x8 board, one row per rank).
//
//   bun scripts/eval-defaults.ts tools/tuning/<file>.params
//
// The section list below must follow the EvalParam layout in
// include/evaluator.h. The generated header static_asserts the total count,
// and the params file's header must match the engine's layout.

import {readFileSync, writeFileSync} from "node:fs";
import {join, basename} from "node:path";

const ENGINE_ROOT = join(import.meta.dir, "..");
const input = process.argv[2];
if (!input) {
    console.error("usage: bun scripts/eval-defaults.ts <tuned.params>");
    process.exit(2);
}

const lines = readFileSync(input, "utf8").split(/\r?\n/);
const header = lines[0].trim();
const m = header.match(/^# jewkiebot-eval v2 (\d+)$/);
if (!m) throw new Error(`not a v2 params file: ${header}`);
const values = lines.slice(1).filter((l) => l.trim() !== "").map(Number);
if (values.length !== Number(m[1]) || values.some((v) => !Number.isInteger(v)))
    throw new Error(`expected ${m[1]} integers, got ${values.length}`);

// [name, entries, per-entry labels or "board"] in EvalParam order.
type Section = [string, number, string[] | "board"];
const SECTIONS: Section[] = [
    ["Material", 5, ["pawn", "knight", "bishop", "rook", "queen"]],
    ["PST pawn", 64, "board"],
    ["PST knight", 64, "board"],
    ["PST bishop", 64, "board"],
    ["PST rook", 64, "board"],
    ["PST queen", 64, "board"],
    ["PST king", 64, "board"],
    ["Passed pawn by relative rank", 8, ["rank 1", "rank 2", "rank 3", "rank 4", "rank 5", "rank 6", "rank 7", "rank 8"]],
    ["Pawn structure", 2, ["doubled (per extra pawn)", "isolated"]],
    ["Pieces", 3, ["bishop pair", "rook on open file", "rook on semi-open file"]],
    ["Mobility per reachable square", 4, ["knight", "bishop", "rook", "queen"]],
    ["King shelter", 3, ["pawn in front", "pawn two ahead", "no pawn on/next to king file"]],
    ["Tempo", 1, ["side to move"]],
];
const total = SECTIONS.reduce((n, s) => n + s[1], 0);
if (2 * total !== values.length) throw new Error(`sections cover ${2 * total} values, file has ${values.length}`);

const pair = (i: number) => `{${values[2 * i]}, ${values[2 * i + 1]}}`.padStart(11);
let out = `// Generated by scripts/eval-defaults.ts from ${basename(input)}. Don't edit by
// hand: re-tune and regenerate. Order and meaning: EvalParam in evaluator.h.
// Each entry is {middlegame, endgame}; piece-square tables are from White's
// side, one row per rank starting with rank 1 (index 0 = a1).
#pragma once

#include "evaluator.h"

inline constexpr EvalScore EVAL_DEFAULTS[EvalParam::COUNT] = {
`;
let i = 0;
for (const [name, n, labels] of SECTIONS) {
    out += `    // ${name}\n`;
    if (labels === "board") {
        for (let rank = 0; rank < 8; ++rank) {
            const row = [];
            for (let file = 0; file < 8; ++file) row.push(pair(i + rank * 8 + file));
            out += `    ${row.join(",")},  // rank ${rank + 1}\n`;
        }
    } else {
        for (let k = 0; k < n; ++k) out += `    ${pair(i + k)},  // ${labels[k]}\n`;
    }
    i += n;
}
out += `};
static_assert(sizeof(EVAL_DEFAULTS) / sizeof(EVAL_DEFAULTS[0]) == EvalParam::COUNT,
              "regenerate src/evalDefaults.h after changing EvalParam");
`;
writeFileSync(join(ENGINE_ROOT, "src", "evalDefaults.h"), out);
console.log(`wrote src/evalDefaults.h (${total} params from ${basename(input)})`);
